/**
 * Единица в форме для числа: (2500, 'пачка') → 'пачек', (2, 'рулон') → 'рулона'.
 * Дробное количество берёт форму «2–4» (2,5 пачки). Незнакомую единицу возвращает null.
 */
export function unitForm(quantity: number, unit: string): string | null {
  const match = /^(\S+)(.*)$/s.exec(unit.trim())
  if (!match || !Number.isFinite(quantity)) return null
  const forms = UNIT_FORMS[match[1].toLowerCase()]
  if (!forms) return null
  const word = Number.isInteger(quantity) ? plural(Math.abs(quantity), ...forms) : forms[1]
  return word + match[2]
}
